export function resolveLegacyPlatformThemeId(themeId?: string | null): string {
  if (!themeId) return DEFAULT_PLATFORM_THEME_ID;
  if (PLATFORM_THEMES.some((t) => t.id === themeId)) return themeId;
  return LEGACY_THEME_MAP[themeId] || DEFAULT_PLATFORM_THEME_ID;
}

export function getPlatformThemeById(themeId?: string | null): PlatformThemeDefinition {
  const resolved = resolveLegacyPlatformThemeId(themeId);
  return PLATFORM_THEMES.find((t) => t.id === resolved) || PLATFORM_THEMES[0];
}

export function isValidPlatformThemeId(themeId: string): boolean {
  return PLATFORM_THEMES.some((t) => t.id === themeId);
}
