import JSZip from 'jszip';
import { Project } from '../types/project';
import { getThemeById } from '../themes';
import { resolveThemeVariables } from '../themes/themeTokens';
import { apiClient } from './apiClient';

function triggerDownload(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export async function exportProjectZip(project: Project): Promise<void> {
  const zip = new JSZip();
  const slug = project.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
  const root = zip.folder(slug || 'aegion-app')!;

  const theme = getThemeById(project.themeId);
  const vars = resolveThemeVariables(theme, project.themeCustomization);

  root.file(
    'README.md',
    `# ${project.name} (${project.version})\n\nGenerated by Aegion AI\n\n- Category: ${project.category}\n- Backend: ${project.language} (${project.framework})\n- Frontend: ${project.frontendFramework}\n- Database: ${project.database}\n- Glass Theme: ${theme.name} (${theme.mode})\n- Modules: ${project.modules.join(', ')}\n`
  );

  root.file(
    'aegion.project-memory.json',
    JSON.stringify(
      {
        id: project.id,
        name: project.name,
        version: project.version,
        category: project.category,
        language: project.language,
        framework: project.framework,
        themeId: project.themeId,
        modules: project.modules,
        memory: project.memory,
      },
      null,
      2
    )
  );

  const cssTokenLines = Object.entries(vars)
    .map(([k, v]) => `  ${k.replace('--preview-', '--app-')}: ${v};`)
    .join('\n');
  root.file('frontend/src/styles/aegion-theme-tokens.css', `:root {\n${cssTokenLines}\n}\n`);

  for (const file of project.files) {
    root.file(file.path, file.content);
  }

  const blob = await zip.generateAsync({ type: 'blob' });
  triggerDownload(blob, `${slug || 'aegion-app'}-${project.version}.zip`);
}

export async function exportPythonBackendScaffoldZip(): Promise<void> {
  const { files } = await apiClient.fetchPythonScaffold();
  const zip = new JSZip();
  for (const file of files) {
    zip.file(file.path, file.content);
  }
  const blob = await zip.generateAsync({ type: 'blob' });
  triggerDownload(blob, 'aegion-python-fastapi-backend.zip');
}
